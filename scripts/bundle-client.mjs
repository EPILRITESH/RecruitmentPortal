// Packs client/dist into server/src/static-bundle.js so the Cloudflare Worker can serve the
// React app itself (no separate static-assets upload needed). Run after `vite build`.
import fs from 'node:fs';
import path from 'node:path';

const dist = path.resolve('client/dist');
const TYPES = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8',
  '.svg': 'image/svg+xml', '.png': 'image/png', '.ico': 'image/x-icon', '.json': 'application/json', '.txt': 'text/plain' };
const files = {};
(function walk(dir) {
  for (const f of fs.readdirSync(dir)) {
    const p = path.join(dir, f);
    if (fs.statSync(p).isDirectory()) { walk(p); continue; }
    const rel = '/' + path.relative(dist, p).split(path.sep).join('/');
    const ext = path.extname(p);
    const text = /^text|json|svg/.test(TYPES[ext] || '');
    files[rel] = { type: TYPES[ext] || 'application/octet-stream', b64: !text, body: text ? fs.readFileSync(p, 'utf8') : fs.readFileSync(p).toString('base64') };
  }
})(dist);
fs.writeFileSync('server/src/static-bundle.js', `// Generated by scripts/bundle-client.mjs – do not edit\nexport default ${JSON.stringify(files)};\n`);
console.log(`Bundled ${Object.keys(files).length} client files`);
